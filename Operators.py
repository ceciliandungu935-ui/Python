#Arithmetic operators - Simple Calculations

x = 900
y = 110

print(x + y) #addition
print(x - y) #subtract
print(x * y) #multiplication
print(x / y)#division
print(x // y)
print(x % y) #modulus - returns reminder

#Comparison Operators
print(x > y)
print(x < y)
print(x >= y)
print(x <= y)
print(x == y)
print(x != y)

#Assignment Operators
number = 19
print(number)

#Operator Precedence
number += 10
print(number)

#Logical Operators - and , or , not
print (30 > 20 and 56==10)
print (30 > 20 or 56==10)
print ( not (30 > 20 and 56==10))


